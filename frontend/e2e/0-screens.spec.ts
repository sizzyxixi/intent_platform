import { expect, test } from '@playwright/test'
import { login, watchErrors } from './helpers'

const out = (n: string) => `../screenshots/${n}.png`

test('主要页面截图', async ({ page }) => {
  const errs = watchErrors(page)
  await login(page)
  await page.screenshot({ path: out('01-意图列表') })
  await page.fill('#fQ', 'B.STOCK.AVAIL'); await page.click('#fApply')
  await expect(page.locator('#intentTbl tbody tr')).toHaveCount(1)
  await page.locator('#intentTbl tbody tr').first().locator('button', { hasText: '编辑' }).click()
  await expect(page.getByTestId('intentEditor')).toBeVisible()
  await page.waitForTimeout(300)
  await page.screenshot({ path: out('02-意图编辑') })
  await page.fill('#tT', '有现货吗，今天能发多少件')
  await page.click('#tRun')
  await expect(page.locator('#tVerdict')).toBeVisible()
  await page.locator('#tOut').scrollIntoViewIfNeeded()
  await page.screenshot({ path: out('03-单句测试') })
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('intentEditor')).toHaveCount(0)
  await page.goto('/#/intents/slots'); await page.waitForTimeout(400)
  await page.screenshot({ path: out('04-槽位') })
  await page.goto('/#/intents/cfg'); await page.waitForTimeout(400)
  await page.screenshot({ path: out('05-空间设置') })
  await page.goto('/#/intents/log'); await page.waitForTimeout(400)
  await page.screenshot({ path: out('06-导入记录') })
  await page.goto('/#/kb'); await expect(page.locator('#kbTbl')).toBeVisible(); await page.waitForTimeout(300)
  await page.screenshot({ path: out('07-知识库列表') })
  await page.goto('/#/kb/kb_aq'); await expect(page.locator('#docTbl')).toBeVisible()
  await page.screenshot({ path: out('08-知识库详情') })
  await page.getByText('知识库检索', { exact: true }).click()
  await page.fill('#ksq', '有现货吗'); await page.click('#kbSearch'); await expect(page.locator('#ksRes')).toBeVisible()
  await page.screenshot({ path: out('09-知识库检索') })
  await page.goto('/#/tools/list'); await expect(page.locator('#toolTbl')).toBeVisible(); await page.waitForTimeout(300)
  await page.screenshot({ path: out('10-工具目录') })
  await page.goto('/#/tools/access'); await expect(page.locator('#keyTbl')).toBeVisible(); await page.waitForTimeout(600)
  await page.screenshot({ path: out('11-接入与密钥') })
  await page.goto('/#/system'); await expect(page.locator('#userTbl')).toBeVisible()
  await page.screenshot({ path: out('12-用户与审计') })
  expect(errs).toEqual([])
})
