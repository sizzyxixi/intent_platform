test('接入与密钥：新建 Key 只显示一次 → 吊销', async ({ page, request }) => {
  await login(page)
  await page.goto('/#/tools/access')
  await page.click('#keyNew')
  await page.fill('#kN', 'E2E Key')
  await page.click('#keyDo')
  const tok = (await page.locator('#kTok').innerText()).trim()
  expect(tok).toMatch(/^ipk_/)
  // 用新 Key 调开放接口
  const r = await request.get('/api/v1/spaces', { headers: { Authorization: 'Bearer ' + tok } })
  expect(r.status()).toBe(200)
  await page.click('#keyDone')
  const row = page.locator('#keyTbl tbody tr', { hasText: 'E2E Key' })
  await expect(row).not.toContainText(tok)
  page.once('dialog', d => d.accept())
  await row.getByRole('button', { name: '吊销' }).click()
  await expect(row).toContainText('已吊销')
  const r2 = await request.get('/api/v1/spaces', { headers: { Authorization: 'Bearer ' + tok } })
  expect(r2.status()).toBe(401)
  // AI 接入说明已加载
  await expect(page.locator('#doc_openapi')).toContainText('openapi: 3')
})

