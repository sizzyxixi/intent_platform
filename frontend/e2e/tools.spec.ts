import { expect, test } from '@playwright/test'
import { login } from './helpers'

test('工具：注册 HTTP 工具 → 测试调用预览 → 删除', async ({ page }) => {
  await login(page)
  await page.goto('/#/tools/list')
  await expect(page.locator('#toolTbl tbody tr')).toHaveCount(29)
  await page.click('#toolNew')
  await page.fill('#tN', 'e2e_query_color')
  await page.fill('#tD', '查颜色')
  await page.fill('#tDs', '按 SKU 查询可选颜色')
  await page.fill('#tU', 'https://erp.example.com/api/color')
  await page.fill('#pN0', 'sku')
  await page.fill('#tO', '{"colors":["红","黑"]}')
  await page.click('#toolSave')
  await expect(page.getByTestId('toolEdit')).toHaveCount(0)
  const row = page.locator('#toolTbl tbody tr', { hasText: 'e2e_query_color' })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: '测试调用' }).click()
  await page.click('#ttRun')
  await expect(page.locator('#ttOut')).toContainText('https://erp.example.com/api/color')
  await page.keyboard.press('Escape')
  page.once('dialog', d => d.accept())
  await row.getByText('删除').click()
  await expect(page.locator('#toolTbl tbody tr', { hasText: 'e2e_query_color' })).toHaveCount(0)
})

