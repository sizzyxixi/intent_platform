test('工具目录：业务分组列，接入与描述单元格紧凑', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await login(page)
  await page.goto('/#/tools/list')
  await expect(page.locator('#toolTbl thead')).toContainText('业务分组')

  await page.fill('#toolQ', 'query_stock')
  const http = page.locator('#toolTbl tbody tr[data-tool="query_stock"]')
  await expect(http).toBeVisible()
  await expect(http.locator('td.grp')).toHaveText('—')

  await page.fill('#toolQ', '')
  await page.locator('#toolTF').getByRole('button', { name: /CLI 命令/ }).click()
  const cli = page.locator('#toolTbl tbody tr[data-tool="xclaw_product_detail"]')
  await expect(cli).toBeVisible()
  await expect(cli.locator('td.grp')).toContainText('商城解决方案')
  await expect(cli.locator('td.grp')).toContainText('商品')
  const end = cli.locator('td.end')
  await expect(end).toContainText('xclaw-cli')
  await expect(end).not.toContainText('鉴权')
  await expect(end).not.toContainText('输出')
  expect(await end.locator('.clamp1').getAttribute('title')).toContain('鉴权')

  const endH = await end.locator('.clamp1').evaluate(el => el.getBoundingClientRect().height)
  expect(endH).toBeLessThanOrEqual(24)
  const rowH = await cli.evaluate(el => el.getBoundingClientRect().height)
  expect(rowH).toBeLessThanOrEqual(96)

  await page.locator('#toolTF').getByRole('button', { name: /^全部 / }).click()
  await page.click('#toolNew')
  await page.fill('#tN', 'e2e_long_desc')
  await page.fill('#tD', '长描述工具')
  await page.fill('#tDs', '这是一段很长的工具描述，用来确认列表里的描述单元格最多显示两行。'.repeat(8))
  await page.fill('#tU', 'https://erp.example.com/api/long-desc')
  await page.fill('#pN0', 'sku')
  await page.click('#toolSave')
  await expect(page.getByTestId('toolEdit')).toHaveCount(0)
  await page.fill('#toolQ', 'e2e_long_desc')
  const longRow = page.locator('#toolTbl tbody tr[data-tool="e2e_long_desc"]')
  await expect(longRow).toBeVisible()
  const desc = longRow.locator('td.desc .clamp2')
  const box = await desc.evaluate(el => {
    const s = getComputedStyle(el)
    const r = el.getBoundingClientRect()
    return { h: r.height, w: r.width, clamp: s.webkitLineClamp || s.lineClamp, overflow: s.overflow, scroll: el.scrollHeight }
  })
  expect(box.w).toBeGreaterThan(80)
  expect(box.h).toBeLessThanOrEqual(42)
  expect(box.scroll).toBeGreaterThan(box.h)
  expect(await longRow.evaluate(el => el.getBoundingClientRect().height)).toBeLessThanOrEqual(96)
  page.once('dialog', d => d.accept())
  await longRow.getByText('删除').click()
  await expect(page.locator('#toolTbl tbody tr[data-tool="e2e_long_desc"]')).toHaveCount(0)
})
