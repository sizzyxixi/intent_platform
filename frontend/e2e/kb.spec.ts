import { expect, test } from '@playwright/test'
import { login, watchErrors } from './helpers'

test('知识库：新建 → 导入示例 → 构建成功 → 切片编辑 → 检索', async ({ page }) => {
  const errs = watchErrors(page)
  await login(page)
  await page.goto('/#/kb')
  await expect(page.locator('#kbTbl tbody tr')).toHaveCount(11)
  await page.click('#kbNew')
  await page.fill('#kiN', 'E2E 开票规则')
  await page.getByRole('button', { name: '开票与发票规则.md' }).click()
  await page.click('#kiOk')
  await expect(page.locator('#kbName')).toHaveText('E2E 开票规则')
  await expect(page.locator('#docTbl tbody tr').first()).toContainText('构建成功', { timeout: 15_000 })
  await page.getByText('知识库详情', { exact: true }).click()
  await expect(page.locator('#chunkTbl tbody tr').first()).toBeVisible()
  await page.locator('#chunkTbl tbody tr').first().getByText('查看').click()
  await page.fill('#cc', '支持普票、专票（E2E 已修改），专票需提供开票资料。')
  await page.fill('#tg_platform', '1688')
  await page.click('#ccSave')
  await expect(page.locator('#chunkTbl')).toContainText('E2E 已修改')
  await page.getByText('知识库检索', { exact: true }).click()
  await page.fill('#ksq', '专票需要什么资料')
  await page.click('#kbSearch')
  await expect(page.locator('#ksRes tbody tr').first()).toContainText('专票')
  expect(errs).toEqual([])
})

test('知识库：同名文档覆盖需确认影响', async ({ page }) => {
  await login(page)
  await page.goto('/#/kb/kb_aq')
  await page.click('#kbImportOpen')
  await page.setInputFiles('#kiF', { name: '物流售后.csv', mimeType: 'text/csv', buffer: Buffer.from('问题,答案,意图编码,适用范围\n多久发货,48 小时内发货,B.SHIP.TIME,全店\n') })
  await page.click('#kiOk')
  await expect(page.getByTestId('kiModal')).toContainText('与已有文档同名或同内容')
  await page.click('#kiOk')
  await expect(page.getByTestId('kiModal').locator('.err')).toContainText('请勾选确认')
  await page.check('#kiAck')
  await page.click('#kiOk')
  await expect(page.getByTestId('kiModal')).toHaveCount(0)
  await expect(page.locator('#docTbl')).toContainText('物流售后.csv')
})
